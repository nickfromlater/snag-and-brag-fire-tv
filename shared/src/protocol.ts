/**
 * The wire contract between phones, the relay and the TV. Version-gated by PROTO.
 *
 *   phone ──ws──▶ relay ──ws──▶ TV (the game host: state machine, timers, bots)
 *
 * The relay holds no game logic. It owns rooms, the clock, photo memory and the AI calls.
 * The TV owns everything else and tells each phone exactly which screen to show.
 *
 * Text frames carry one JSON `ClientToRelay` / `RelayToClient` object.
 * Binary frames are `[u32 BE header length][header JSON, UTF-8][payload bytes]`
 * (see encodeBinary/decodeBinary). Photos and thumbnails only ever travel as binary
 * and live only in relay memory for the life of the room. Nothing is written to disk
 * or logs.
 *
 * All times on the wire are relay-clock milliseconds (`serverNow`), synced with ping/pong.
 */
import type { Reaction, RoundKind } from './constants';

export const PROTO = 1;
/** The relay accepts WebSocket upgrades only on this path. */
export const WS_PATH = '/ws';

/* =====================================================================
   Relay envelope
   ===================================================================== */

/** A phone's persistent id: random 128-bit hex generated once and kept in localStorage.
 *  It is the reconnect token. Only the relay and the TV ever see it. */
export type ClientId = string;
/** 4 uppercase letters, no vowels-only words; generated by the relay. */
export type RoomCode = string;
export type TeamId = string;
export type PhotoId = string;

export type ClientToRelay =
  | { t: 'hello'; proto: number; role: 'tv'; resume?: { code: RoomCode; tvKey: string } }
  | { t: 'hello'; proto: number; role: 'phone'; code: RoomCode; cid: ClientId }
  | { t: 'ping'; c: number }
  /** TV → phones. `to` is a list of client ids or 'all'. */
  | { t: 'to'; to: ClientId[] | 'all'; m: TvToPhone }
  /** Phone → TV. */
  | { t: 'msg'; m: PhoneToTv }
  /** TV asks for Sir Socksworth's voice (Polly). */
  | { t: 'tts'; id: string; text: string }
  /** TV ends the room: the relay drops every photo and closes every socket. */
  | { t: 'close' };

export type RelayToClient =
  | {
      t: 'welcome';
      role: 'tv' | 'phone';
      code: RoomCode;
      /** TV only: proves ownership when the TV reconnects. */
      tvKey?: string;
      /** Read key for GET /p/:code/:photoId?k= and /tts/:code/:id?k= */
      roomKey: string;
      /** Phone URL to put in the QR code, e.g. https://<host>/?r=K7QF */
      joinUrl: string;
      serverNow: number;
    }
  | { t: 'error'; code: 'NO_ROOM' | 'ROOM_FULL' | 'BAD_PROTO' | 'BAD_KEY' | 'RATE_LIMIT' | 'BAD_MSG'; detail?: string }
  | { t: 'pong'; c: number; s: number }
  /** To the TV: a phone connected or dropped. */
  | { t: 'peer'; cid: ClientId; up: boolean }
  /** To the TV: a phone's message, stamped with who sent it and when the relay got it. */
  | { t: 'from'; cid: ClientId; at: number; m: PhoneToTv | SnagArrived }
  /** To a phone: the TV's message. */
  | { t: 'msg'; m: TvToPhone }
  /** To the TV and the snagging phone: the AI read of a photo (or the fallback). */
  | { t: 'ai'; cid: ClientId; photoId: PhotoId; r: AiRead }
  /** To the TV: the voice line is ready at GET /tts/:code/:id?k=roomKey (audio/mpeg). */
  | { t: 'tts'; id: string; ok: boolean; marks?: SpeechMark[]; durationMs?: number };

/** Binary frame headers. */
export type BinaryHeader =
  /** phone → relay → TV, 3 per second while hunting. Payload: JPEG about 96x64. */
  | { t: 'thumb'; cid?: ClientId }
  /** phone → relay. Payload: 720x720 JPEG at q .8. The relay stores it, answers the TV
   *  with a SnagArrived and starts the AI read. `redaction` is an optional,
   *  non-identifying method metric; the relay accepts and ignores it. */
  | { t: 'snag'; round: number; hex: string; match: number; prompt: string; roundKind: RoundKind;
      /** Optional 24×24 Pixel Judge mask (72 bytes, standard base64); absent for bots and other rounds. */
      mask?: string; redaction?: 'mediapipe' | 'shape' | 'none' };

/** What the TV receives for a snag (the JPEG stays in the relay; fetch it by photoId). */
export interface SnagArrived {
  t: 'snag';
  photoId: PhotoId;
  round: number;
  /** Pixel Judge result computed on the phone. */
  hex: string;
  match: number;
  /** Optional 24×24 Pixel Judge mask (72 bytes, standard base64); absent for bots and other rounds. */
  mask?: string;
}

export interface AiRead {
  /** Plain name of the object, 1-4 words. */
  thing: string;
  /** Three stage names, each under 18 characters. */
  names: string[];
  /** Two brag lines, each under 60 characters. */
  brags: string[];
  /** 0-10: how well it fits the prompt. Tie-breaker. */
  score: number;
  /** One host line, under 80 characters. */
  quip: string;
  /** True when Bedrock timed out or failed and this came from the fallback lists. */
  fallback: boolean;
}

export interface SpeechMark { time: number; type: 'viseme' | 'word'; value: string }

/* =====================================================================
   Game messages: phone → TV
   ===================================================================== */

export type PhoneToTv =
  | { t: 'join'; name: string; color: string }
  /** Host phone only, after the 0.85 s hold. */
  | { t: 'start' }
  /** Host phone only: fill the room with bots (solo demo mode). */
  | { t: 'bots'; on: boolean }
  /** Glow-up result. Eyes are in the sticker's 120-unit box. */
  | { t: 'glow'; eyes: [[number, number], [number, number]]; name: string; brag: string }
  /** Taps since the last send (every 100 ms while mashing); side -1 = left, 1 = right. */
  | { t: 'tap'; n: number; side: -1 | 1 }
  | { t: 'vote'; team: TeamId }
  | { t: 'react'; kind: Reaction }
  /** Host phone only. */
  | { t: 'control'; action: 'skip' | 'pause' | 'resume' | 'end' }
  /** End screen: Run it back (host phone restarts; others just rejoin). */
  | { t: 'again' };

/* =====================================================================
   Game messages: TV → phone
   ===================================================================== */

export type TvToPhone =
  /** The whole screen. Idempotent: a reconnecting phone gets the latest one and is current. */
  | ScreenMsg
  /** A rival snagged, etc. "Couch Potatoes snagged a red mug". */
  | { t: 'toast'; text: string; color: string }
  /** Points landed for this phone's team: confetti + rolling number. */
  | { t: 'award'; pts: number; total: number }
  /** Live tug position during a mash, 5 Hz. -1 = left wins, 1 = right wins. */
  | { t: 'mashp'; p: number };

export interface TeamView {
  id: TeamId;
  name: string;
  mono: string;
  color: string;
  score: number;
  bot: boolean;
  connected: boolean;
  /** False only for a neutral TV lobby slot; absent means a joined team (including dropouts). */
  joined?: boolean;
}

export interface PromptView {
  kind: RoundKind;
  a: string;
  b: string;
  c: string;
  /** Accent color of the big word. */
  col: string;
  /** Color Rush target swatch. */
  hex?: string;
}

/** A find as any screen draws it: a real photo (photoId) or a bot's SVG sticker (obj). */
export interface FindView {
  team: TeamId;
  round: number;
  photoId?: PhotoId;
  /** Bot finds: the ART id of the sticker (e.g. 'mug'). */
  obj?: string;
  /** Stage name. */
  name: string;
  brag: string;
  /** What it is ("rubber glove"), from the AI or the bot's object. */
  thing: string;
  /** Two googly eyes in the 120-unit sticker box, plus the eye radius. */
  eyes?: [[number, number], [number, number], number];
  /** The photo's judged color. */
  hex?: string;
  match?: number;
  /** Optional 24×24 Pixel Judge mask (72 bytes, standard base64); absent for bots and other rounds. */
  mask?: string;
  /** Seconds from SNAG! to the shutter. */
  time?: number;
  pts?: number;
  /** "Didn't snag": worth 0, no pedestal, gives a bye. */
  missed?: boolean;
}

export interface FighterView { team: TeamView; find: FindView; side: -1 | 1 }

export type Screen =
  | { k: 'join'; takenColors: string[]; suggestedName: string; full: boolean }
  | { k: 'lobby'; isHost: boolean; canStart: boolean; botsOn: boolean; minTeams: number }
  /** Round intro on the phone. `prompt` appears once the reel lands; `count` during 3-2-1. */
  | { k: 'ready'; kicker: string; title: string; sub: string; prompt?: PromptView; count?: '3' | '2' | '1' | 'GO!' }
  /** Hunting. Use the common prompt and deadline. `snagged` is the toast list so far. */
  | { k: 'cam' }
  /** Glow-up. Names and brags fill in when the AI read lands (aiPending false). */
  | { k: 'glow'; find: FindView; names: string[]; brags: string[]; aiPending: boolean }
  | { k: 'wait'; msg: string; sub?: string; card?: FindView }
  | {
      k: 'mash';
      kicker: string;
      youIn: boolean;
      left: FighterView;
      right: FighterView;
      phase: 'ready' | 'mash' | 'done';
      head?: string;
      sub?: string;
    }
  | { k: 'vote'; options: FindView[]; voted?: TeamId }
  | {
      k: 'end';
      rank: number;
      line: string;
      best?: FindView;
      rows: { round: number; name: string; sub: string; pts: number }[];
      isHost: boolean;
    };

export interface ScreenMsg {
  t: 'screen';
  /** Increases with every screen the TV sends; phones drop stale ones. */
  seq: number;
  /** This phone's team, once joined. */
  me: TeamView | null;
  /** Every team in seat order (for the roster and rank list). */
  teams: TeamView[];
  /** -1 in the lobby, 0..2 during rounds, 3 at the finale. */
  round: number;
  prompt?: PromptView;
  /** Relay-clock ms when the current timer ends, and its full length. */
  deadline?: number;
  total?: number;
  paused: boolean;
  s: Screen;
}

/* =====================================================================
   UTF-8 without relying on TextEncoder/TextDecoder: Hermes on the React Native 0.72
   runtime Vega ships may not have them, and decodeBinary runs on every feed thumbnail.
   ===================================================================== */

const HAS_TEXT_CODEC = typeof TextEncoder !== 'undefined' && typeof TextDecoder !== 'undefined';

export function utf8Encode(s: string): Uint8Array {
  return HAS_TEXT_CODEC ? new TextEncoder().encode(s) : utf8EncodeJs(s);
}

export function utf8Decode(b: Uint8Array): string {
  return HAS_TEXT_CODEC ? new TextDecoder().decode(b) : utf8DecodeJs(b);
}

/** Pure-JS UTF-8 encode (exported for tests). */
export function utf8EncodeJs(s: string): Uint8Array {
  const out: number[] = [];
  for (let i = 0; i < s.length; i++) {
    let c = s.charCodeAt(i);
    if (c >= 0xd800 && c <= 0xdbff && i + 1 < s.length) {
      const d = s.charCodeAt(i + 1);
      if (d >= 0xdc00 && d <= 0xdfff) { c = 0x10000 + ((c - 0xd800) << 10) + (d - 0xdc00); i++; }
    }
    if (c < 0x80) out.push(c);
    else if (c < 0x800) out.push(0xc0 | (c >> 6), 0x80 | (c & 63));
    else if (c < 0x10000) out.push(0xe0 | (c >> 12), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
    else out.push(0xf0 | (c >> 18), 0x80 | ((c >> 12) & 63), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
  }
  return Uint8Array.from(out);
}

/** Pure-JS UTF-8 decode (exported for tests). */
export function utf8DecodeJs(b: Uint8Array): string {
  let s = '';
  for (let i = 0; i < b.length; ) {
    const c = b[i++]!;
    let cp: number;
    if (c < 0x80) cp = c;
    else if (c < 0xe0) cp = ((c & 31) << 6) | (b[i++]! & 63);
    else if (c < 0xf0) cp = ((c & 15) << 12) | ((b[i++]! & 63) << 6) | (b[i++]! & 63);
    else cp = ((c & 7) << 18) | ((b[i++]! & 63) << 12) | ((b[i++]! & 63) << 6) | (b[i++]! & 63);
    s += String.fromCodePoint(cp);
  }
  return s;
}

/* =====================================================================
   Binary framing (works in browsers, Node and React Native)
   ===================================================================== */

export function encodeBinary(header: BinaryHeader, payload: Uint8Array): Uint8Array {
  const h = utf8Encode(JSON.stringify(header));
  const out = new Uint8Array(4 + h.length + payload.length);
  new DataView(out.buffer).setUint32(0, h.length, false);
  out.set(h, 4);
  out.set(payload, 4 + h.length);
  return out;
}

export function decodeBinary(buf: ArrayBuffer | Uint8Array): { header: BinaryHeader; payload: Uint8Array } | null {
  const u = buf instanceof Uint8Array ? buf : new Uint8Array(buf);
  if (u.length < 4) return null;
  const n = new DataView(u.buffer, u.byteOffset, u.byteLength).getUint32(0, false);
  if (n > 4096 || 4 + n > u.length) return null;
  try {
    const header = JSON.parse(utf8Decode(u.subarray(4, 4 + n))) as BinaryHeader;
    return { header, payload: u.subarray(4 + n) };
  } catch {
    return null;
  }
}

/* =====================================================================
   Clock sync
   ===================================================================== */

/** Keeps a running estimate of (relay clock − local clock) from ping/pong samples.
 *  Uses the samples with the lowest round trip, which carry the least error. */
export class ClockSync {
  private samples: { rtt: number; off: number }[] = [];
  offset = 0;
  rtt = Infinity;
  constructor(private readonly now: () => number) {}
  /** Call with the pong. c = local send time echoed back, s = relay time. */
  sample(c: number, s: number): void {
    const t = this.now();
    const rtt = t - c;
    if (rtt < 0 || rtt > 10000) return;
    this.samples.push({ rtt, off: s - (c + rtt / 2) });
    if (this.samples.length > 12) this.samples.shift();
    const best = [...this.samples].sort((a, b) => a.rtt - b.rtt).slice(0, 4);
    this.offset = best.reduce((a, b) => a + b.off, 0) / best.length;
    this.rtt = best[0]!.rtt;
  }
  /** Relay-clock now. */
  serverNow(): number {
    return this.now() + this.offset;
  }
  /** Local-clock time of a relay-clock instant. */
  toLocal(serverMs: number): number {
    return serverMs - this.offset;
  }
}
